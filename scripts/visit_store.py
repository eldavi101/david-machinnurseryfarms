"""First-party visit totals using SQLite, with atomic session deduplication."""
import hashlib
import sqlite3
import time
import uuid
from contextlib import contextmanager
from pathlib import Path


class VisitStore:
    def __init__(self, database):
        self.database = Path(database)
        self.database.parent.mkdir(parents=True, exist_ok=True)
        with self.connect() as connection:
            connection.execute("PRAGMA journal_mode=WAL")
            connection.execute("CREATE TABLE IF NOT EXISTS totals (id INTEGER PRIMARY KEY CHECK (id = 1), count INTEGER NOT NULL)")
            connection.execute("INSERT OR IGNORE INTO totals VALUES (1, 0)")
            connection.execute("CREATE TABLE IF NOT EXISTS sessions (digest TEXT PRIMARY KEY, expires INTEGER NOT NULL)")
            connection.execute("CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires)")

    @contextmanager
    def connect(self):
        connection = sqlite3.connect(self.database, timeout=15)
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    def total(self):
        with self.connect() as connection:
            return connection.execute("SELECT count FROM totals WHERE id = 1").fetchone()[0]

    def record(self, session):
        # UUIDs are generated by the browser, never derived from IPs or user data.
        if not isinstance(session, str) or len(session) != 36:
            raise ValueError("Invalid session")
        parsed = uuid.UUID(session)
        if parsed.version != 4 or str(parsed) != session:
            raise ValueError("Invalid session")
        digest = hashlib.sha256(session.encode("ascii")).hexdigest()
        now = int(time.time())
        with self.connect() as connection:
            connection.execute("BEGIN IMMEDIATE")
            connection.execute("DELETE FROM sessions WHERE expires <= ?", (now,))
            inserted = connection.execute("INSERT OR IGNORE INTO sessions VALUES (?, ?)", (digest, now + 30 * 86400)).rowcount
            if inserted:
                connection.execute("UPDATE totals SET count = count + 1 WHERE id = 1")
            return connection.execute("SELECT count FROM totals WHERE id = 1").fetchone()[0]

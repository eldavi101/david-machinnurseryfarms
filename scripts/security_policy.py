"""Generate real HTML protections and the equivalent server/edge header policy."""
import base64
import hashlib
import json
import re
from pathlib import Path


def digest(content):
    return "sha256-" + base64.b64encode(hashlib.sha256(content).digest()).decode("ascii")


def policy(script_hash, inline_scripts=(), analytics=False, extra_hashes=()):
    scripts = [f"'{value}'" for value in (script_hash, *extra_hashes)] + [f"'{digest(s.encode('utf-8'))}'" for s in inline_scripts]
    if analytics:
        scripts.append("https://www.googletagmanager.com")
    connections = "'self' https://www.google-analytics.com https://region1.google-analytics.com https://www.googletagmanager.com" if analytics else "'self'"
    return "; ".join([
        "default-src 'none'", "base-uri 'none'", "object-src 'none'",
        "script-src " + " ".join(dict.fromkeys(scripts)), "script-src-attr 'none'",
        "style-src 'self'", "style-src-attr 'none'", "img-src 'self'",
        "font-src 'self'", "connect-src " + connections, "frame-src 'none'",
        "worker-src 'none'", "manifest-src 'self'", "form-action 'none'",
        "upgrade-insecure-requests",
    ])


def response_headers(csp):
    return {
        "Strict-Transport-Security": "max-age=31536000",
        "Content-Security-Policy": csp + "; frame-ancestors 'none'",
        "X-Frame-Options": "DENY",
        "X-Content-Type-Options": "nosniff",
        "Referrer-Policy": "no-referrer",
        "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=(), accelerometer=(), gyroscope=(), magnetometer=(), browsing-topics=()",
        "Cross-Origin-Embedder-Policy": "require-corp",
        "Cross-Origin-Opener-Policy": "same-origin",
        "Cross-Origin-Resource-Policy": "same-origin",
    }


def headers_for_site(directory):
    """Collect policies from generated pages, preserving analytics and JSON-LD hashes."""
    policies = []
    for page in sorted(Path(directory).rglob("*.html")):
        content = page.read_text(encoding="utf-8")
        from html import unescape
        match = re.search(r'<meta http-equiv="Content-Security-Policy" content="([^"]+)"', content)
        if match:
            policies.append(unescape(match[1]))
    if not policies:
        raise ValueError("No generated CSP policies found")
    directives = {}
    for csp in policies:
        for directive in csp.split("; "):
            name, *values = directive.split()
            directives.setdefault(name, [])
            for value in values:
                if value not in directives[name]: directives[name].append(value)
    csp = "; ".join(" ".join([name, *values]) for name, values in directives.items())
    return response_headers(csp)


def write_edge_policy(directory, root):
    headers = headers_for_site(directory)
    content = "/*\n" + "\n".join(f"  {key}: {value}" for key, value in headers.items()) + "\n"
    (Path(directory) / "_headers").write_text(content, encoding="utf-8")
    target = Path(root) / "edge/policy.mjs"
    target.parent.mkdir(exist_ok=True)
    target.write_text("// Generated by scripts/package_site.py. GitHub Pages does not apply these headers.\nexport default " + json.dumps(headers, indent=2) + ";\n", encoding="utf-8")
